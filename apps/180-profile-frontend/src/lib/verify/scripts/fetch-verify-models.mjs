#!/usr/bin/env node
/**
 * 180 Verify — populate public/verify-models with self-hosted MediaPipe assets.
 *
 *   node src/lib/verify/scripts/fetch-verify-models.mjs          (from apps/180-profile-frontend)
 *
 * 1. Copies the Tasks Vision WASM runtime (SIMD + non-SIMD builds) from node_modules.
 * 2. Downloads face_landmarker.task and blaze_face_short_range.tflite from Google's model bucket.
 * Idempotent: existing files are kept unless --force is passed.
 *
 * If these files are absent at runtime the page falls back to jsDelivr / storage.googleapis.com.
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(here, '../../../..');
const outDir = join(appRoot, 'public', 'verify-models');
const wasmOut = join(outDir, 'wasm');
const force = process.argv.includes('--force');

const MODELS = [
  {
    file: 'face_landmarker.task',
    url: 'https://storage.googleapis.com/mediapipe-models/face_landmarker/face_landmarker/float16/1/face_landmarker.task',
  },
  {
    file: 'blaze_face_short_range.tflite',
    url: 'https://storage.googleapis.com/mediapipe-models/face_detector/blaze_face_short_range/float16/1/blaze_face_short_range.tflite',
  },
];
const WASM_FILES = ['vision_wasm_internal.js', 'vision_wasm_internal.wasm', 'vision_wasm_nosimd_internal.js', 'vision_wasm_nosimd_internal.wasm'];

mkdirSync(wasmOut, { recursive: true });

// The package's `exports` map hides package.json, so locate it by walking up node_modules (works with hoisting).
function findPackageDir(name) {
  let dir = appRoot;
  for (;;) {
    const candidate = join(dir, 'node_modules', name);
    if (existsSync(join(candidate, 'package.json'))) return candidate;
    const parent = dirname(dir);
    if (parent === dir) throw new Error(`${name} not found — run pnpm install first`);
    dir = parent;
  }
}
const pkgDir = findPackageDir('@mediapipe/tasks-vision');
const wasmSrc = join(pkgDir, 'wasm');
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;
console.log(`@mediapipe/tasks-vision ${version}`);

for (const f of WASM_FILES) {
  const dest = join(wasmOut, f);
  if (!force && existsSync(dest) && statSync(dest).size === statSync(join(wasmSrc, f)).size) {
    console.log(`  = wasm/${f}`);
    continue;
  }
  copyFileSync(join(wasmSrc, f), dest);
  console.log(`  + wasm/${f}`);
}

for (const m of MODELS) {
  const dest = join(outDir, m.file);
  if (!force && existsSync(dest) && statSync(dest).size > 0) {
    console.log(`  = ${m.file}`);
    continue;
  }
  const res = await fetch(m.url);
  if (!res.ok) throw new Error(`Download failed (${res.status}) for ${m.url}`);
  const buf = Buffer.from(await res.arrayBuffer());
  writeFileSync(dest, buf);
  console.log(`  + ${m.file} (${(buf.length / 1024 / 1024).toFixed(2)} MB)`);
}

writeFileSync(
  join(outDir, 'VERSION.txt'),
  `@mediapipe/tasks-vision ${version}\nGenerated by src/lib/verify/scripts/fetch-verify-models.mjs\n`,
);
console.log(`Done → ${outDir}`);
